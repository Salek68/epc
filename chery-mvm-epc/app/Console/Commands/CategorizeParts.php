    private function classify(string $name): array
    {
        $name = mb_strtolower(trim($name));

        foreach ($this->rules as $category => $subcategories) {
            foreach ($subcategories as $subcategory => $keywords) {
                foreach ($keywords as $keyword) {
                    if (mb_strpos($name, mb_strtolower($keyword)) !== false) {
                        return [$category, $subcategory];
                    }
                }
            }
        }

        return ['متفرقه / نیازمند بررسی', 'دسته‌بندی نشده'];
    }

    public function handle(): int
    {
        $total = DB::table('parts')
            ->where('category_manual', false)
            ->count();

        $this->info("Parts to classify: {$total}");

        DB::table('parts')
            ->select('id', 'name_fa')
            ->where('category_manual', false)
            ->orderBy('id')
            ->chunkById(500, function ($parts) {
                $groups = [];

                foreach ($parts as $part) {
                    [$category, $subcategory] = $this->classify(
                        (string) $part->name_fa
                    );

                    $key = $category . '||' . $subcategory;
                    $groups[$key][] = $part->id;
                }

                foreach ($groups as $key => $ids) {
                    [$category, $subcategory] = explode('||', $key, 2);

                    foreach (array_chunk($ids, 200) as $idChunk) {
                        DB::table('parts')
                            ->whereIn('id', $idChunk)
                            ->update([
                                'category' => $category,
                                'subcategory' => $subcategory,
                            ]);
                    }
                }

                $this->output->write('.');
            });

        $this->newLine();
        $this->info('Categorization complete.');

        $summary = DB::table('parts')
            ->select('category', DB::raw('COUNT(*) AS total'))
            ->groupBy('category')
            ->orderByDesc('total')
            ->get();

        foreach ($summary as $item) {
            $this->line($item->category . ': ' . $item->total);
        }

        return self::SUCCESS;
    }
